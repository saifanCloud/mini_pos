/// Konstanta jarak (spacing) dan radius standar untuk UI POS kasir.
class AppSpacing {
  AppSpacing._();

  /// 4.0 dp - Jarak mikro antar elemen kecil
  static const double xs = 4.0;

  /// 8.0 dp - Jarak kecil (padding internal tombol, antar baris teks)
  static const double sm = 8.0;

  /// 12.0 dp - Jarak sedang (padding card kompak, antar form field)
  static const double md = 12.0;

  /// 16.0 dp - Jarak standar (margin halaman mobile, padding card utama)
  static const double lg = 16.0;

  /// 24.0 dp - Jarak besar (antar section, padding dialog)
  static const double xl = 24.0;

  /// 32.0 dp - Jarak ekstra besar (header, empty state spacing)
  static const double xxl = 32.0;
}

/// Konstanta sudut membulat (border radius) standar.
class AppRadius {
  AppRadius._();

  /// 6.0 dp - Sudut kecil untuk badge atau chip mikro
  static const double xs = 6.0;

  /// 8.0 dp - Sudut kecil untuk elemen kompak
  static const double sm = 8.0;

  /// 12.0 dp - Sudut sedang untuk tombol, input text field, dan item list
  static const double md = 12.0;

  /// 16.0 dp - Sudut standar untuk Card dan kartu produk
  static const double lg = 16.0;

  /// 20.0 dp - Sudut besar untuk BottomSheet dan Dialog
  static const double xl = 20.0;

  /// 999.0 dp - Bulat penuh (pill button, status circle)
  static const double full = 999.0;
}

